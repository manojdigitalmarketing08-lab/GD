#!/usr/bin/env python3
"""Bundle the small source stylesheets into the three files the pages load.

Run this after editing anything in css/ and upload the bundles:

    python tools/build-css.py

The source files stay in css/ so they are easy to edit; the pages only
reference the bundles, which saves 3-5 render-blocking requests per page.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS = os.path.join(ROOT, 'css')

BUNDLES = {
    # home, about, contact, thank-you, 404
    'site.css': ['fonts.css', 'partials.css', 'styles.css', 'brand.css'],
    # the store-style service pages
    'services.css': ['fonts.css', 'partials.css', 'service.css', 'brand.css', 'store.css', 'store-pages.css'],
    # the Local SEO page
    'service-local.css': ['fonts.css', 'partials.css', 'service.css', 'brand.css', 'local-seo.css'],
}


def squeeze(css):
    css = css.replace('﻿', '')                               # a BOM mid-bundle would break the next selector
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)           # comments (data: URLs contain no "/*")
    lines = [ln.strip() for ln in css.splitlines()]
    return '\n'.join(ln for ln in lines if ln) + '\n'


for out, parts in BUNDLES.items():
    body = ''.join(squeeze(open(os.path.join(CSS, p), encoding='utf8').read()) for p in parts)
    with open(os.path.join(CSS, out), 'w', encoding='utf8', newline='\n') as fh:
        fh.write('/* GENERATED by tools/build-css.py - edit the source files, not this one. */\n' + body)
    print('%-18s %6d bytes  <- %s' % (out, len(body.encode('utf8')), ', '.join(parts)))
